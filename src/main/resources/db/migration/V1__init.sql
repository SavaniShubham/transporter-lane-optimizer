-- Transporter Lane Optimizer Database Schema
-- Version: V1
-- Description: Initial schema for lanes, transporters, and lane quotes

CREATE TABLE IF NOT EXISTS lanes (
    id BIGINT PRIMARY KEY,
    origin VARCHAR(255) NOT NULL,
    destination VARCHAR(255) NOT NULL
);

CREATE TABLE IF NOT EXISTS transporters (
    id BIGINT PRIMARY KEY,
    name VARCHAR(255) NOT NULL
);

CREATE TABLE IF NOT EXISTS lane_quotes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transporter_id BIGINT NOT NULL,
    lane_id BIGINT NOT NULL,
    quote BIGINT NOT NULL,
    CONSTRAINT fk_quotes_transporter FOREIGN KEY (transporter_id) REFERENCES transporters(id) ON DELETE CASCADE,
    CONSTRAINT fk_quotes_lane FOREIGN KEY (lane_id) REFERENCES lanes(id) ON DELETE CASCADE,
    CONSTRAINT uq_transporter_lane UNIQUE (transporter_id, lane_id)
);

CREATE INDEX IF NOT EXISTS idx_quotes_lane_id ON lane_quotes (lane_id);
CREATE INDEX IF NOT EXISTS idx_quotes_transporter_id ON lane_quotes (transporter_id);
